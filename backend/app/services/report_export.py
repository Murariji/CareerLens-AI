"""Turn an analysis into a downloadable report: PDF, Word (.doc) or Markdown.

Everything is generated on our own server with libraries already installed
(PyMuPDF for PDF), so downloads cost nothing and the report is never stored.
"""

from __future__ import annotations

import io
import re
from datetime import date
from html import escape

import pymupdf

from app.schemas import AnalysisResponse

READINESS_LABEL = {
    "ready_to_apply": "Ready to apply",
    "apply_after_updates": "Apply after a focused update",
    "build_evidence_first": "Build evidence first",
}


def report_filename(report: AnalysisResponse, extension: str) -> str:
    role = re.sub(r"[^a-z0-9]+", "-", report.target_role.lower()).strip("-")[:40] or "report"
    return f"careerlens-{role}-{date.today().isoformat()}.{extension}"


def _strengths(report: AnalysisResponse) -> list[tuple[str, str, bool]]:
    if report.ai_analysis and report.ai_analysis.strengths:
        return [(s.skill, s.resume_evidence, True) for s in report.ai_analysis.strengths]
    return [(e.skill, e.evidence, e.demonstrated) for e in report.skill_evidence]


def _gaps(report: AnalysisResponse) -> list[tuple[str, str, str]]:
    """(skill, label, how to close)."""

    if report.ai_analysis and report.ai_analysis.gaps:
        return [(g.skill, f'Job asks: "{g.job_requirement}"', g.how_to_close) for g in report.ai_analysis.gaps]
    return [(g.skill, "required" if g.required else "good to have", g.project_idea) for g in report.gaps]


def _suggestions(report: AnalysisResponse) -> list[str]:
    if report.ai_analysis and report.ai_analysis.resume_suggestions:
        return report.ai_analysis.resume_suggestions
    return report.resume_suggestions


def _questions(report: AnalysisResponse) -> list[tuple[str, str]]:
    if report.ai_analysis and report.ai_analysis.interview_questions:
        return [(q.question, q.why_asked) for q in report.ai_analysis.interview_questions]
    return []


# ---------------------------------------------------------------- Markdown

def build_markdown(report: AnalysisResponse) -> str:
    lines: list[str] = [
        f"# CareerLens report: {report.target_role}",
        "",
        f"*{report.location + ' · ' if report.location else ''}Generated {date.today().isoformat()} · "
        f"{'AI + rules' if report.ai_analysis else 'Rule-based'} analysis*",
        "",
        f"## Match score: {report.match_score}%",
        "",
        report.summary,
        "",
        report.message,
        "",
        f"- Required skills: {report.required_matched}/{report.required_total}",
        f"- Good-to-have skills: {report.bonus_matched}/{report.bonus_total}",
    ]
    if report.ats:
        lines.append(f"- ATS checks passed: {report.ats.passed}/{report.ats.total}")

    plan = report.application_plan
    lines += ["", f"## Next best action: {READINESS_LABEL[plan.readiness]}", "", f"**{plan.headline}** {plan.reason}", ""]
    lines += [f"{i}. {action}" for i, action in enumerate(plan.next_actions, 1)]

    lines += ["", "## Strengths with proof", ""]
    for skill, evidence, demonstrated in _strengths(report):
        note = "" if demonstrated else " *(listed only)*"
        lines.append(f"- **{skill}**{note}" + (f": \"{evidence}\"" if evidence else ""))

    lines += ["", "## Gaps and how to close them", ""]
    for skill, label, how in _gaps(report):
        lines.append(f"- **{skill}** ({label}): {how}")

    if report.ai_analysis and report.ai_analysis.bullet_rewrites:
        lines += ["", "## Bullet rewrites", ""]
        for rewrite in report.ai_analysis.bullet_rewrites:
            lines += [f"- Before: {rewrite.original}", f"  - After: **{rewrite.improved}**", f"  - Why: {rewrite.why}"]

    lines += ["", "## Priority edits", ""]
    lines += [f"{i}. {s}" for i, s in enumerate(_suggestions(report), 1)]

    if report.ats:
        lines += ["", f"## ATS checklist ({report.ats.passed}/{report.ats.total})", ""]
        lines += [f"- [{'x' if c.passed else ' '}] **{c.label}**: {c.detail}" for c in report.ats.checks]

    questions = _questions(report)
    if questions:
        lines += ["", "## Interview questions to prepare", ""]
        lines += [f"{i}. **{q}**  \n   {why}" for i, (q, why) in enumerate(questions, 1)]

    lines += ["", "---", "Generated by CareerLens AI · https://careerlens-ai-lite.netlify.app", ""]
    return "\n".join(lines)


# ---------------------------------------------------------------- HTML (shared by PDF and Word)

REPORT_CSS = """
body { font-family: sans-serif; font-size: 10.5pt; color: #121826; line-height: 1.45; }
h1 { font-size: 19pt; color: #4c2ee0; margin: 0 0 2pt 0; }
h2 { font-size: 13pt; color: #121826; margin: 14pt 0 5pt 0; border-bottom: 1px solid #d9dcea; padding-bottom: 2pt; }
.meta { color: #5d6679; font-size: 9pt; margin: 0 0 8pt 0; }
.score { font-size: 26pt; font-weight: bold; color: #4c2ee0; margin: 4pt 0; }
.muted { color: #5d6679; }
.good { color: #047857; font-weight: bold; }
.bad { color: #be123c; font-weight: bold; }
.quote { color: #5d6679; font-style: italic; }
td, th { padding: 3pt 6pt; border: 1px solid #d9dcea; vertical-align: top; font-size: 9.5pt; }
th { background-color: #f1efff; text-align: left; }
table { border-collapse: collapse; width: 100%; }
li { margin-bottom: 3pt; }
"""


def build_html(report: AnalysisResponse) -> str:
    e = escape
    plan = report.application_plan
    parts: list[str] = [
        f"<h1>CareerLens report: {e(report.target_role)}</h1>",
        f"<p class='meta'>{e(report.location + ' · ') if report.location else ''}Generated {date.today().isoformat()} · "
        f"{'AI + rules' if report.ai_analysis else 'Rule-based'} analysis</p>",
        f"<p class='score'>{report.match_score}% match</p>",
        f"<p><b>{e(report.summary)}</b></p>",
        f"<p>{e(report.message)}</p>",
        "<table><tr><th>Required skills</th><th>Good-to-have</th><th>ATS checks</th></tr>",
        f"<tr><td>{report.required_matched}/{report.required_total}</td><td>{report.bonus_matched}/{report.bonus_total}</td>"
        f"<td>{f'{report.ats.passed}/{report.ats.total}' if report.ats else '-'}</td></tr></table>",
        f"<h2>Next best action: {e(READINESS_LABEL[plan.readiness])}</h2>",
        f"<p><b>{e(plan.headline)}</b> {e(plan.reason)}</p>",
        "<ol>" + "".join(f"<li>{e(a)}</li>" for a in plan.next_actions) + "</ol>",
        "<h2>Strengths with proof</h2><ul>",
    ]
    for skill, evidence, demonstrated in _strengths(report):
        tag = "" if demonstrated else " <span class='muted'>(listed only)</span>"
        quote = f"<br/><span class='quote'>“{e(evidence)}”</span>" if evidence else ""
        parts.append(f"<li><span class='good'>{e(skill)}</span>{tag}{quote}</li>")
    parts.append("</ul><h2>Gaps and how to close them</h2><ul>")
    for skill, label, how in _gaps(report):
        parts.append(f"<li><span class='bad'>{e(skill)}</span> <span class='muted'>({e(label)})</span><br/>{e(how)}</li>")
    parts.append("</ul>")

    if report.ai_analysis and report.ai_analysis.bullet_rewrites:
        parts.append("<h2>Bullet rewrites</h2><table><tr><th>Before</th><th>After</th></tr>")
        for r in report.ai_analysis.bullet_rewrites:
            parts.append(f"<tr><td class='muted'>{e(r.original)}</td><td><b>{e(r.improved)}</b><br/><span class='muted'>{e(r.why)}</span></td></tr>")
        parts.append("</table>")

    parts.append("<h2>Priority edits</h2><ol>" + "".join(f"<li>{e(s)}</li>" for s in _suggestions(report)) + "</ol>")

    if report.ats:
        parts.append(f"<h2>ATS checklist ({report.ats.passed}/{report.ats.total})</h2><table>")
        for c in report.ats.checks:
            mark = "<span class='good'>PASS</span>" if c.passed else "<span class='bad'>FIX</span>"
            parts.append(f"<tr><td>{mark}</td><td><b>{e(c.label)}</b><br/><span class='muted'>{e(c.detail)}</span></td></tr>")
        parts.append("</table>")

    questions = _questions(report)
    if questions:
        parts.append("<h2>Interview questions to prepare</h2><ol>")
        parts += [f"<li><b>{e(q)}</b><br/><span class='muted'>{e(why)}</span></li>" for q, why in questions]
        parts.append("</ol>")

    parts.append("<p class='meta'>Generated by CareerLens AI · careerlens-ai-lite.netlify.app</p>")
    return "".join(parts)


def build_doc(report: AnalysisResponse) -> bytes:
    """An HTML document saved as .doc: opens in Microsoft Word, Google Docs and LibreOffice."""

    document = (
        "<html xmlns:o='urn:schemas-microsoft-com:office:office' xmlns:w='urn:schemas-microsoft-com:office:word' "
        "xmlns='http://www.w3.org/TR/REC-html40'><head><meta charset='utf-8'>"
        f"<title>CareerLens report</title><style>{REPORT_CSS}</style></head><body>{build_html(report)}</body></html>"
    )
    return document.encode("utf-8")


def build_pdf(report: AnalysisResponse) -> bytes:
    buffer = io.BytesIO()
    story = pymupdf.Story(html=build_html(report), user_css=REPORT_CSS)
    writer = pymupdf.DocumentWriter(buffer)
    page = pymupdf.paper_rect("a4")
    content = page + (42, 42, -42, -42)
    more = True
    while more:
        device = writer.begin_page(page)
        more, _ = story.place(content)
        story.draw(device)
        writer.end_page()
    writer.close()
    return buffer.getvalue()
